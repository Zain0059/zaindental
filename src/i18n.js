let _currentLang = "ar"; // Default to Arabic as requested!

try {
  const saved = localStorage.getItem("zd_lang");
  if (saved === "en" || saved === "ar") {
    _currentLang = saved;
  }
} catch (e) {}

export function getLang() {
  return _currentLang;
}

export function isAr() {
  return _currentLang === "ar";
}

export function t(key, fallback = "") {
  const langDict = DICT[_currentLang] || DICT.ar;
  if (langDict && key in langDict) {
    return langDict[key];
  }
  return fallback || key;
}

export function setLanguage(lang) {
  if (lang !== "ar" && lang !== "en") lang = "ar";
  _currentLang = lang;
  try {
    localStorage.setItem("zd_lang", lang);
  } catch (e) {}

  applyLangToDOM();

  // Trigger UI re-renders if app is active
  if (window.refreshCurrentView) {
    window.refreshCurrentView();
  }
}

export function toggleLanguage() {
  const newLang = _currentLang === "ar" ? "en" : "ar";
  setLanguage(newLang);
}

export function applyLangToDOM() {
  const isArabic = _currentLang === "ar";
  document.documentElement.lang = _currentLang;
  document.documentElement.dir = isArabic ? "rtl" : "ltr";
  document.body.classList.toggle("rtl-mode", isArabic);

  // Update dynamic elements marked with data-i18n
  document.querySelectorAll("[data-i18n]").forEach(el => {
    const key = el.getAttribute("data-i18n");
    if (key && DICT[_currentLang] && DICT[_currentLang][key]) {
      el.textContent = DICT[_currentLang][key];
    }
  });

  // Update placeholder translations marked with data-i18n-ph
  document.querySelectorAll("[data-i18n-ph]").forEach(el => {
    const key = el.getAttribute("data-i18n-ph");
    if (key && DICT[_currentLang] && DICT[_currentLang][key]) {
      el.placeholder = DICT[_currentLang][key];
    }
  });

  // Update titles
  document.querySelectorAll("[data-i18n-title]").forEach(el => {
    const key = el.getAttribute("data-i18n-title");
    if (key && DICT[_currentLang] && DICT[_currentLang][key]) {
      el.title = DICT[_currentLang][key];
    }
  });

  // Update Language toggle buttons
  document.querySelectorAll(".lang-toggle-btn").forEach(btn => {
    const labelSpan = btn.querySelector(".lang-label") || btn;
    labelSpan.textContent = isArabic ? "English" : "العربية";
  });
}
